const NOT_A_PERSON = /\b(GRUPO|CONSTRUCTOR|CONTABILIDAD|INMOBILIARIA|INVERSIONES|EMPRESA|ASESOR|ASESORA|SAS|LTDA|TIENDA|VENTAS|CONFECCIONES|DIOS|BENDIGA|BENDICION|FAMILIA|INNOVA|STORE|SHOP|DISTRIBUIDORA)\b/;

const norm = (s: string) => s.normalize('NFD').replace(/[̀-ͯ]/g, '').toUpperCase();

export function personFirstName(name: string | undefined | null): string {
  const raw = String(name ?? '').trim();
  if (!raw || /^lead\b/i.test(raw) || /\d/.test(raw)) return '';
  if (NOT_A_PERSON.test(norm(raw))) return '';
  const first = raw.replace(/[^\p{L}\s'-]/gu, ' ').trim().split(/\s+/)[0] ?? '';
  if (first.length < 2) return '';
  if (/\p{Ll}\p{Lu}/u.test(first)) return ''; // "ApuRito"
  if (!COMMON_FIRST_NAMES.has(norm(first))) return '';
  return first.charAt(0).toUpperCase() + first.slice(1).toLowerCase();
}
